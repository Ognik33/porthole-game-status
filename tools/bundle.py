#!/usr/bin/env python3
"""Склеивает модули src/*.luau в один main.luau.

Песочница Porthole не находит модули внутри папки дополнения через require, поэтому
модули объединяются при сборке. Каждый модуль становится функцией, require("./имя")
заменяется на __req("имя"). Точка входа — src/main.luau.
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "src"
args = [a for a in sys.argv[1:] if not a.startswith("--")]
lib_mode = "--lib" in sys.argv  # for tests: return __req instead of running main
out = pathlib.Path(args[0]) if args else root / "build" / "main.luau"

REQ = re.compile(r'require\(\s*"\./([A-Za-z0-9_]+)"\s*\)')
mods = {p.stem: p.read_text(encoding="utf-8") for p in sorted(src.glob("*.luau"))}
if "main" not in mods:
    sys.exit("src/main.luau is missing")

used = set()
for name, text in mods.items():
    for dep in REQ.findall(text):
        if dep not in mods:
            sys.exit(f"{name}.luau requires unknown module {dep!r}")
        used.add(dep)

parts = [
    "-- Generated by tools/bundle.py from src/*.luau. Do not edit; edit src/ instead.",
    "local __mods, __cache, __loading = {}, {}, {}",
    "local function __req(name)",
    "\tlocal c = __cache[name]",
    "\tif c ~= nil then return c end",
    "\tif __loading[name] then error(\"circular require: \" .. name) end",
    "\t__loading[name] = true",
    "\tc = __mods[name]()",
    "\t__loading[name] = nil",
    "\t__cache[name] = c == nil and true or c",
    "\treturn __cache[name]",
    "end",
]
for name in sorted(mods):
    if name == "main":
        continue
    body = REQ.sub(lambda m: f'__req("{m.group(1)}")', mods[name])
    parts.append(f'__mods["{name}"] = function()\n{body}\nend')
if lib_mode:
    parts.append("return __req")
else:
    parts.append("-- entry point: src/main.luau")
    parts.append(REQ.sub(lambda m: f'__req("{m.group(1)}")', mods["main"]))
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(parts) + "\n", encoding="utf-8")
print(f"bundled {len(mods)} modules -> {out}")
